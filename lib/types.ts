export type Severity = 'Critical' | 'High' | 'Medium' | 'Low'
export type IssueStatus = 'Open' | 'Reviewed' | 'Fixed'

export type IssueCategory =
  | 'Security'
  | 'Complexity'
  | 'Maintainability'
  | 'Dependencies'
  | 'Code Quality'

export interface LanguageShare {
  name: string
  percent: number
  color: string
}
      
export interface Repository {
  owner: string
  name: string
  fullName: string
  description: string
  url: string
  branch: string
  stars: number
  forks: number
  openIssues: number
  files: number
  sourceFiles: number
  functions: number
  classes: number
  modules: number
  dependencies: number
  tests: number
  languages: LanguageShare[]
  lastCommit: string
  license: string
  /** GitHub-only fields. Present once /api/analysis enriches the bundle. */
  watchers?: number
  topics?: string[]
  defaultBranch?: string
}

/**
 * Optional AI-written narrative layered on top of the deterministic summary.
 * Generated by lib/analysis/llm.ts from the same computed facts the template
 * summary uses; absent when no LLM is configured (the UI falls back to
 * `AnalysisOverview.summary`).
 */
export interface RepoNarrative {
  /** Plain-language paragraph: what the project is for. */
  purpose: string
  /** Bullet points describing how the project works. */
  howItWorks: string[]
  /** Short architecture / component labels. */
  architecture: string[]
  /** Notable strengths grounded in the facts. */
  strengths: string[]
  /** Risks or gaps worth a reviewer's attention. */
  risks: string[]
  /** Model identifier that produced the narrative. */
  model: string
  generatedAt: string
}

/**
 * The full, detailed repo report shown on the Deep Analysis page. Generated by
 * lib/analysis/llm.ts from code insights (import graph, routes, models, config,
 * file excerpts) that cannot be seen on the GitHub page. Every claim can carry
 * the file paths that support it so the report is verifiable.
 */
export interface DeepAnalysis {
  purpose: string
  whatItDoes: string
  architecture: Array<{
    component: string
    responsibility: string
    connectsTo: string[]
    /** Exact files (with `:line` where known) that justify this component. */
    files?: string[]
  }>
  dataFlow: Array<{ step: string; detail: string; files: string[] }>
  domainModel: Array<{
    entity: string
    fields: string[]
    relations: string[]
    /** Where the entity is declared, e.g. `prisma/schema.prisma`. */
    file?: string
    line?: number
  }>
  keyModules: Array<{
    name: string
    role: string
    keyFiles: string[]
    /** Declared symbol names inside the module (AST). */
    symbols?: string[]
  }>
  techStack: Array<{ name: string; role: string; why: string }>
  howToRun: string[]
  onboarding: string[]
  strengths: string[]
  risks: string[]
  /** Files with the highest churn × size score. */
  hotspots?: Array<{ file: string; commits: number; insertions: number; deletions: number; score: number }>
  contributors?: Array<{ name: string; commits: number }>
  commitCount?: number | null
  model: string
  generatedAt: string
  /**
   * Where the report came from: an LLM (`ai`) or the deterministic static
   * analysis (`deterministic`). Absent on older cached reports, treated as `ai`.
   */
  source?: 'ai' | 'deterministic'
  /**
   * Total number of dependencies and their health status.
   * Populated by the deterministic report from ProjectFacts.
   */
  totalDependencies?: number
  dependencyHealth?: { healthy: number; review: number; vulnerable: number }
}

export interface AnalysisStep {
  id: string
  label: string
  detail: string
}

/** A repository file that has landed on disk inside the runner container. */
export interface CloneFileEntry {
  /** Repo-relative path, e.g. `src/app/page.tsx`. */
  path: string
  bytes: number
  /** Seconds since epoch, from the container's `stat`. */
  mtime: number
}

/** Latest phase reported by `git clone --progress`. */
export interface CloneProgress {
  phase: string
  percent: number
  /** Everything git printed after the percentage (size, speed, done). */
  detail: string | null
}

/**
 * Live clone telemetry from /api/clone/status. While the runner is fetching,
 * `bytes`/`fileCount` grow and `files` carries the most recently written
 * entries so the Analyze page can show each file as it is pulled.
 */
export interface CloneStatus {
  state: 'cloning' | 'done' | 'failed'
  exitCode: number | null
  /** Disk usage of /workspace/repo, including git metadata. */
  bytes: number
  /** Files in the working tree (`.git` internals excluded). */
  fileCount: number
  /** Newest files first, capped server-side. */
  files: CloneFileEntry[]
  progress: CloneProgress | null
  /** Clone failure reason, when `state` is `failed`. */
  error: string | null
  /** Last few meaningful lines from the git progress log. */
  log: string[]
}

